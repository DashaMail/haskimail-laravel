<?php

declare(strict_types=1);

namespace Haskimail\Laravel\Transport;

use Haskimail\Laravel\Exceptions\InvalidMessageException;
use Haskimail\Laravel\HaskimailClient;
use Haskimail\Laravel\Mail\Headers\HaskimailHeader;
use Haskimail\Laravel\Mail\Headers\TemplateHeader;
use Haskimail\Laravel\Support\AddressFormatter;
use Haskimail\Laravel\Support\MessageValidator;
use Symfony\Component\Mailer\Envelope;
use Symfony\Component\Mailer\Header\MetadataHeader;
use Symfony\Component\Mailer\Header\TagHeader;
use Symfony\Component\Mime\Address;
use Symfony\Component\Mime\Email;
use Symfony\Component\Mime\Header\HeaderInterface;
use Symfony\Component\Mime\Header\ParameterizedHeader;
use Symfony\Component\Mime\Header\UnstructuredHeader;
use Symfony\Component\Mime\Part\DataPart;

/**
 * Converts a Symfony Email into a Haskimail API payload.
 *
 * @internal
 */
final class PayloadFactory
{
    /**
     * Headers that are expressed through dedicated API fields or generated by Haskimail.
     */
    private const RESERVED_HEADERS = [
        'from', 'to', 'cc', 'bcc', 'subject', 'reply-to', 'sender', 'return-path', 'date',
        'mime-version', 'content-type', 'content-transfer-encoding', 'content-disposition',
    ];

    /**
     * Extensions rejected by Haskimail, see https://haskimail.ru/developer/user-guide/send-email-with-api.
     */
    public const FORBIDDEN_EXTENSIONS = [
        'vbs', 'exe', 'bin', 'bat', 'chm', 'com', 'cpl', 'crt', 'hlp', 'hta', 'inf', 'ins', 'isp', 'jse',
        'lnk', 'mdb', 'pcd', 'pif', 'reg', 'scr', 'sct', 'shs', 'vbe', 'vba', 'wsf', 'wsh', 'wsl', 'msc',
        'msi', 'msp', 'mst',
    ];

    public function __construct(private readonly ?string $defaultMessageStream = null) {}

    public function make(Email $email, Envelope $envelope): TransportPayload
    {
        $payload = [];
        $template = null;
        $html = $this->bodyToString($email->getHtmlBody());
        $text = $this->bodyToString($email->getTextBody());

        $payload['From'] = AddressFormatter::format($this->sender($email, $envelope));

        [$to, $cc, $bcc] = $this->recipients($email, $envelope);
        $payload['To'] = AddressFormatter::formatList($to);

        if ($cc !== []) {
            $payload['Cc'] = AddressFormatter::formatList($cc);
        }

        if ($bcc !== []) {
            $payload['Bcc'] = AddressFormatter::formatList($bcc);
        }

        if ($email->getReplyTo() !== []) {
            $payload['ReplyTo'] = AddressFormatter::formatList($email->getReplyTo());
        }

        $subject = $email->getSubject();
        if ($subject !== null && trim($subject) !== '') {
            // Line breaks and control characters are not meaningful in a subject, and the
            // API would turn a line break into a new header: flatten them.
            $payload['Subject'] = trim((string) preg_replace('/\s*[\x00-\x1F\x7F\x{0085}\x{2028}\x{2029}]+\s*/u', ' ', $subject));
        }

        $customHeaders = [];
        $metadata = [];
        $tags = [];
        $stream = $this->defaultMessageStream;

        foreach ($email->getHeaders()->all() as $header) {
            if (! $header instanceof HeaderInterface) {
                continue;
            }

            $name = $header->getName();
            $lower = strtolower($name);

            if ($header instanceof TagHeader) {
                $tags[] = $this->singleLine('Tag', $header->getValue());

                continue;
            }

            if ($header instanceof MetadataHeader) {
                $key = $this->singleLine('Metadata key', $header->getKey());
                $metadata[$key] = $this->singleLine('Metadata "'.$key.'"', $header->getValue());

                continue;
            }

            if ($header instanceof TemplateHeader) {
                $template = $header;

                continue;
            }

            if (str_starts_with($lower, strtolower(HaskimailHeader::PREFIX))) {
                $value = trim($this->singleLine($name, $this->rawValue($header)));

                match ($lower) {
                    strtolower(HaskimailHeader::MESSAGE_STREAM) => $stream = $value,
                    strtolower(HaskimailHeader::TRACK_OPENS) => $payload['TrackOpens'] = $this->parseBool($name, $value),
                    strtolower(HaskimailHeader::TRACK_LINKS) => $payload['TrackLinks'] = $this->parseBool($name, $value),
                    strtolower(HaskimailHeader::TEMPLATE) => $template = new TemplateHeader(ctype_digit($value) ? (int) $value : $value),
                    default => throw new InvalidMessageException(sprintf('Unknown Haskimail control header "%s".', $name)),
                };

                continue;
            }

            if (in_array($lower, self::RESERVED_HEADERS, true)) {
                continue;
            }

            $customHeaders[] = ['Name' => $name, 'Value' => $this->headerValue($header)];
        }

        if (count($tags) > 1) {
            throw new InvalidMessageException('Haskimail allows a single tag per message, '.count($tags).' given.');
        }

        if ($tags !== []) {
            $payload['Tag'] = $tags[0];
        }

        if ($customHeaders !== []) {
            $payload['Headers'] = $customHeaders;
        }

        if ($metadata !== []) {
            $payload['Metadata'] = $metadata;
        }

        $attachments = $this->attachments($email, $html);
        if ($attachments !== []) {
            $payload['Attachments'] = $attachments;
        }

        if ($stream !== null && $stream !== '') {
            $payload['MessageStream'] = $this->singleLine('MessageStream', $stream);
        }

        if ($template instanceof TemplateHeader) {
            $id = $template->template();
            $templateFields = is_int($id)
                ? ['TemplateId' => $id]
                : ['TemplateAlias' => $this->singleLine('TemplateAlias', $id)];
            // An empty PHP array would be encoded as a JSON list; the API expects an object.
            $templateFields['TemplateModel'] = (object) $template->model();

            return new TransportPayload(true, $templateFields + $payload);
        }

        if ($html === null && $text === null) {
            throw new InvalidMessageException('A message needs an HTML body, a text body, or a Haskimail template.');
        }

        if ($html !== null) {
            $payload['HtmlBody'] = $html;
        }

        if ($text !== null) {
            $payload['TextBody'] = $text;
        }

        return new TransportPayload(false, $payload);
    }

    private function sender(Email $email, Envelope $envelope): Address
    {
        $from = $email->getFrom();

        if (count($from) > 1) {
            throw new InvalidMessageException('Haskimail accepts exactly one "From" address.');
        }

        return $from[0] ?? $envelope->getSender();
    }

    /**
     * @return array{0: list<Address>, 1: list<Address>, 2: list<Address>}
     */
    private function recipients(Email $email, Envelope $envelope): array
    {
        $to = array_values($email->getTo());
        $cc = array_values($email->getCc());
        $seen = [];

        foreach ([...$to, ...$cc] as $address) {
            $seen[strtolower($address->getAddress())] = true;
        }

        // Every envelope recipient that is not visible in To/Cc is a blind copy,
        // which also covers recipients added by Mail::alwaysTo() or a custom Envelope.
        $bcc = [];
        foreach ($envelope->getRecipients() as $address) {
            $key = strtolower($address->getAddress());

            if (! isset($seen[$key])) {
                $seen[$key] = true;
                $bcc[] = $address;
            }
        }

        if ($to === []) {
            throw new InvalidMessageException('Haskimail requires at least one "To" recipient.');
        }

        $total = count($to) + count($cc) + count($bcc);
        if ($total > HaskimailClient::MAX_RECIPIENTS) {
            throw new InvalidMessageException(sprintf(
                'Haskimail accepts at most %d recipients (To, Cc and Bcc combined), %d given.',
                HaskimailClient::MAX_RECIPIENTS,
                $total,
            ));
        }

        return [$to, $cc, $bcc];
    }

    /**
     * @return list<array{Name: string, Content: string, ContentType: string, ContentID?: string}>
     */
    private function attachments(Email $email, ?string $html): array
    {
        $result = [];

        foreach ($email->getAttachments() as $part) {
            $name = $this->attachmentName($part);
            // "x.exe." / "x.exe::$DATA" still count as .exe.
            $extension = strtolower((string) preg_replace('/[^A-Za-z0-9].*$/s', '', pathinfo(rtrim($name, '. '), PATHINFO_EXTENSION)));

            if (in_array($extension, self::FORBIDDEN_EXTENSIONS, true)) {
                throw new InvalidMessageException(sprintf('Attachments with the ".%s" extension are rejected by Haskimail ("%s").', $extension, $name));
            }

            $attachment = [
                'Name' => $name,
                'Content' => base64_encode($part->getBody()),
                'ContentType' => MessageValidator::mediaType($part->getMediaType().'/'.$part->getMediaSubtype()),
            ];

            if ($part->getDisposition() === 'inline') {
                $attachment['ContentID'] = 'cid:'.$this->contentId($part, $name, $html);
            }

            $result[] = $attachment;
        }

        return $result;
    }

    private function attachmentName(DataPart $part): string
    {
        $name = $part->getFilename() ?? '';
        // Never let a file name carry a path, header-breaking or invisible characters
        // (a U+202E override can disguise "fdp.exe" as "exe.pdf").
        $name = basename(str_replace('\\', '/', $name));
        $name = trim((string) preg_replace('/[\p{Cc}\p{Cf}\p{Zl}\p{Zp}"]+/u', '', $name));

        return $name !== '' ? $name : 'attachment';
    }

    /**
     * Resolve the Content-ID the HTML body actually references.
     *
     * Laravel's $message->embed() and Symfony's Email::embed() reference "cid:<name>",
     * while an explicit DataPart::setContentId() is referenced as "cid:<content-id>".
     */
    private function contentId(DataPart $part, string $name, ?string $html): string
    {
        if ($part->hasContentId()) {
            $id = $part->getContentId();

            if ($html === null || str_contains($html, 'cid:'.$id)) {
                return $id;
            }
        }

        return $name;
    }

    private function headerValue(HeaderInterface $header): string
    {
        $name = $header->getName();

        MessageValidator::headerName($name);

        return $this->singleLine('Header "'.$name.'"', $this->rawValue($header));
    }

    /**
     * The header value as the user set it: raw UTF-8 for text headers (the API
     * encodes them itself), the rendered and unfolded form for structured ones.
     */
    private function rawValue(HeaderInterface $header): string
    {
        if ($header instanceof UnstructuredHeader && ! $header instanceof ParameterizedHeader) {
            return $header->getValue();
        }

        return (string) preg_replace('/\r\n[ \t]+/', ' ', $header->getBodyAsString());
    }

    private function singleLine(string $field, string $value): string
    {
        return MessageValidator::singleLine($field, $value);
    }

    private function parseBool(string $header, string $value): bool
    {
        return match (strtolower($value)) {
            'true', '1', 'yes', 'on' => true,
            'false', '0', 'no', 'off' => false,
            default => throw new InvalidMessageException(sprintf('Header "%s" must be "true" or "false", "%s" given.', $header, $value)),
        };
    }

    /**
     * @param  resource|string|null  $body
     */
    private function bodyToString(mixed $body): ?string
    {
        if (is_resource($body)) {
            if (stream_get_meta_data($body)['seekable']) {
                rewind($body);
            }

            $body = stream_get_contents($body);

            if ($body === false) {
                throw new InvalidMessageException('Unable to read the message body stream.');
            }
        }

        return is_string($body) ? $body : null;
    }
}
